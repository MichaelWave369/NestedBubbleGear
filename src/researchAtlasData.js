export const findResearch = (query = '', category = 'All') => {
  const s = query.trim().toLowerCase()
  return RESEARCH_TRACKS.filter(track =>
    (category === 'All' || track.category === category) &&
    (!s || [track.id, track.title, track.summary, track.category, track.status, track.note].join(' ').toLowerCase().includes(s))
  )
}
