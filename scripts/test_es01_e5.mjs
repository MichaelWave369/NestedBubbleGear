import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {ES01_E5_FIELDS,makeES01ReviewPacket} from '../src/es01ReviewPacket.js'
const src=p=>readFileSync(p,'utf8')
const evidence=JSON.parse(src('src/es01Evidence.json'))
const e2=JSON.parse(src('src/es01ClaimAudit.json'))
const e3=JSON.parse(src('src/es01Hypotheses.json'))
const e4=JSON.parse(src('src/es01Readiness.json'))
assert.equal(ES01_E5_FIELDS.length,6)
const ids=new Set()
for(const r of evidence.records){
  assert(!ids.has(r.id));ids.add(r.id)
  const packet=makeES01ReviewPacket(r.id)
  assert.equal(packet.schema,'ES01-E5-REVIEW-HANDOFF')
  assert.equal(packet.status,'DRAFT_UNVERIFIED')
  assert.equal(packet.evaluationAuthority,'NONE')
  assert.equal(packet.verifiedByIndependentReviewer,false)
  assert.equal(packet.source.url,r.source.url)
  assert.equal(packet.source.title,r.source.title)
  assert.equal(packet.source.recordId,r.id)
  const provenance=e2.records.find(x=>x.recordId===r.id)
  const hyp=e3.records.find(x=>x.sourceRecordId===r.id)
  const screen=e4.records.find(x=>x.recordId===r.id)
  assert.equal(packet.sourceCustody.sourceSupported,provenance.supported)
  assert.equal(packet.sourceCustody.notEstablished,provenance.notEstablished)
  assert.equal(packet.researchQuestion.id,hyp.id)
  assert.equal(packet.readiness.gate,'HOLD_REVIEW_INCOMPLETE')
  assert.equal(packet.readiness.prohibitedInference,screen.prohibitedInference)
  assert.equal(packet.readiness.requiredFields.length,6)
  assert.equal(packet.intake.filledCount,0)
  assert.equal(packet.intake.blankFields.length,6)
  assert.equal(packet.decisions.claimPromoted,false)
  assert.equal(packet.decisions.clinicalEfficacyInferred,false)
  assert.equal(packet.decisions.quantitativeComparisonAuthorized,false)
  const input=Object.fromEntries(ES01_E5_FIELDS.map(x=>[x.key,'  Reviewer draft: '+x.label+'  ']))
  const filled=makeES01ReviewPacket(r.id,input)
  assert.equal(filled.intake.filledCount,6)
  assert.equal(filled.status,'DRAFT_UNVERIFIED')
  assert.equal(filled.readiness.gate,'HOLD_REVIEW_INCOMPLETE')
  assert.equal(filled.decisions.claimPromoted,false)
  assert(filled.reviewerNotes.fullMethods.startsWith('Reviewer draft:'))
  const partial=makeES01ReviewPacket(r.id,{fullMethods:'   '})
  assert.equal(partial.intake.filledCount,0)
  assert.equal(partial.source.url,r.source.url)
}
assert.throws(()=>makeES01ReviewPacket('DOES_NOT_EXIST'),/source-linked/)
const truncation=makeES01ReviewPacket(evidence.records[0].id,{fullMethods:'x'.repeat(5000),extra:'SHOULD_NOT_EXPORT'})
assert.equal(truncation.reviewerNotes.fullMethods.length,4000)
assert(!('extra' in truncation.reviewerNotes))
const ui=src('src/ES01ReviewHandoff.jsx'),explorer=src('src/ES01Explorer.jsx'),css=src('src/es01Explorer.css')
for(const token of ['useState','maxLength={4000}','Blob','URL.createObjectURL','URL.revokeObjectURL','document.createElement','DRAFT_UNVERIFIED','aria-live','noopener noreferrer','Export draft JSON'])assert(ui.includes(token),'UI missing '+token)
assert(explorer.includes('<ES01ReviewHandoff />'))
assert(css.includes('.es01-e5')&&css.includes('@media(max-width:760px)'))
const protocol=src('docs/ES01_E5_REVIEW_HANDOFF.md')
for(const token of ['DRAFT_UNVERIFIED','HOLD_REVIEW_INCOMPLETE','NOT_EXTRACTED','NOT_SEARCHED','no new server','Ledger Above Ego'])assert(protocol.toLowerCase().includes(token.toLowerCase()),'missing protocol '+token)
assert(src('src/researchAtlasData.js').includes("row('ES-01-E5'"))
assert(JSON.parse(src('package.json')).scripts.test.includes('test:es01-e5'))
console.log('PASS ES-01 E5: ten bounded, source-bound reviewer packet exports with no claim promotion')
