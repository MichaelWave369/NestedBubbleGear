import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import {ES01_E4_FIELDS,checkES01ReviewReadiness} from '../src/es01ReadinessModel.js'
const load=p=>JSON.parse(readFileSync(p,'utf8'))
const src=p=>readFileSync(p,'utf8')
const evidence=load('src/es01Evidence.json'),e2=load('src/es01ClaimAudit.json'),e3=load('src/es01Hypotheses.json'),e4=load('src/es01Readiness.json')
assert.equal(e4.schema,'ES01-E4-READINESS-LEDGER')
assert.equal(e4.status,'LITERATURE_REVIEW_NOT_COMPLETED')
assert.equal(e4.records.length,evidence.records.length)
assert.equal(ES01_E4_FIELDS.length,6)
const sources=new Map(evidence.records.map(x=>[x.id,x]))
const audits=new Set(e2.records.map(x=>x.recordId))
const questions=new Map(e3.records.map(x=>[x.sourceRecordId,x.id]))
const ids=new Set()
for(const r of e4.records){
 assert(!ids.has(r.recordId));ids.add(r.recordId)
 assert(sources.has(r.recordId)&&audits.has(r.recordId)&&questions.get(r.recordId)===r.hypothesisId)
 assert.equal(r.reviewState,'SCREENING_REQUIRED')
 const gate=checkES01ReviewReadiness(r)
 assert.equal(gate.result,'HOLD_REVIEW_INCOMPLETE')
 assert.equal(gate.canInferClinicalBenefit,false)
 assert.equal(gate.canPoolEffectEstimates,false)
 assert.equal(gate.blockers.length,6)
 for(const field of ES01_E4_FIELDS)assert.equal(r[field.key],field.pending,'unexpected status for '+r.recordId+'/'+field.key)
 for(const k of ['nextExtraction','mostImportantConfound','prohibitedInference'])assert(typeof r[k]==='string'&&r[k].length>65,'missing '+k+'/'+r.recordId)
}
assert.deepEqual(ids,new Set(evidence.records.map(r=>r.id)))
for(const mutated of [{recordId:'test',fullMethods:'COMPLETE',benefitEndpoint:'COMPLETE',harmEndpoint:'COMPLETE',comparability:'COMPLETE',riskOfBias:'COMPLETE',replicationSearch:'COMPLETE'},e4.records[0]])assert.equal(checkES01ReviewReadiness(mutated).result,'HOLD_REVIEW_INCOMPLETE')
assert.throws(()=>checkES01ReviewReadiness({recordId:'bad'}),/missing review gate/)
const ui=src('src/ES01ReadinessPanel.jsx'),explorer=src('src/ES01Explorer.jsx'),css=src('src/es01Explorer.css'),doc=src('docs/ES01_E4_EVIDENCE_READINESS.md')
for(const token of ['useState','aria-live','HOLD_REVIEW_INCOMPLETE','ES01_E4_FIELDS','nextExtraction','mostImportantConfound','prohibitedInference','noopener noreferrer'])assert(ui.includes(token),'missing UI '+token)
assert(explorer.includes('<ES01ReadinessPanel />'))
assert(css.includes('.es01-e4'))
for(const token of ['NOT_EXTRACTED does not mean NOT_REPORTED','NOT_SEARCHED does not mean NO_REPLICATION_EXISTS','HOLD_REVIEW_INCOMPLETE','Ledger Above Ego'])assert(doc.includes(token))
assert(src('src/researchAtlasData.js').includes("row('ES-01-E4'"))
assert(JSON.parse(src('package.json')).scripts.test.includes('test:es01-e4'))
console.log('PASS ES-01 E4: ten source-bound screening queues, six pending domains each, all inference gates held')
