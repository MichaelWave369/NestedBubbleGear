import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const load=p=>JSON.parse(readFileSync(p,'utf8'))
const original=load('src/es01Evidence.json')
const audits=load('src/es01ClaimAudit.json')
const src=p=>readFileSync(p,'utf8')
assert.equal(audits.schema,'ES01-CLAIM-CUSTODY-E2')
assert(audits.status.includes('NO INDEPENDENT REPLICATION'))
assert.equal(audits.records.length,original.records.length)
assert.equal(new Set(audits.records.map(x=>x.recordId)).size,original.records.length)
assert.deepEqual(new Set(audits.records.map(x=>x.family)),new Set(original.families))
const map=new Map(audits.records.map(x=>[x.recordId,x]))
for(const entry of original.records){
 const a=map.get(entry.id)
 assert(a,'missing provenance for '+entry.id)
 assert.equal(a.sourceUrl,entry.source.url,'source URL mismatch '+entry.id)
 assert.equal(a.sourceTitle,entry.source.title,'title mismatch '+entry.id)
 assert.equal(a.family,entry.family)
 assert.equal(a.compound,entry.compound)
 assert.equal(a.reviewStatus,'SCOPE_CHECKED_NOT_REPLICATED')
 assert(['ABSTRACT_SCOPE','REGULATORY_SCOPE'].includes(a.scopeLevel))
 assert.equal(a.reviewDate,'2026-10-27')
 for(const key of ['observedSetting','supported','notEstablished','basis','endpointKind','primaryLocation'])assert(typeof a[key]==='string'&&a[key].length>=25,'missing '+key+' '+entry.id)
 assert(!/verified human cure|proved no hallucinations in humans|non-addictive in humans/i.test(a.supported))
}
for(const id of ['ES01-LSD-JRT','ES01-OPI-DFNZ','ES01-PSI-L5','ES01-DMT-1A','ES01-MDMA-RMDDMA'])assert.equal(map.get(id).scopeLevel,'ABSTRACT_SCOPE')
assert.equal(map.get('ES01-CAN-CBD').scopeLevel,'REGULATORY_SCOPE')
assert.equal(map.get('ES01-KET-ESK').scopeLevel,'REGULATORY_SCOPE')
const mdma=map.get('ES01-MDA-COMP');assert(mdma.observedSetting.includes('23 healthy volunteers')&&mdma.notEstablished.includes('PTSD'))
const metabolism=map.get('ES01-MDMA-MDA-MET');assert(metabolism.observedSetting.includes('139 healthy volunteers'))
const ket=map.get('ES01-KET-HNK');assert(/Phase 1|Phase 1/i.test(ket.endpointKind))
const ui=src('src/ES01Explorer.jsx'),doc=src('docs/ES01_E2_CLAIM_PROVENANCE.md')
for(const token of ['es01ClaimAudit.json','Claim provenance','<details','<summary','notEstablished','supported','r.source.url'])assert(ui.includes(token),'missing UI element '+token)
for(const token of ['SCOPE_CHECKED_NOT_REPLICATED','139 participants','23-person','not a PTSD outcome trial','Ledger Above Ego'])assert(doc.includes(token),'missing doc '+token)
assert(src('src/es01Explorer.css').includes('.es01-audit'))
assert(src('package.json').includes('test:es01-e2'))
const index=src('src/researchAtlasData.js');assert(index.includes("row('ES-01-E2'"))
console.log('PASS ES-01 E2 claim custody: '+audits.records.length+' source-bound audits, no clinical promotion')
