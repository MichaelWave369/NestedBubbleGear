import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {makeES01ReviewPacket,ES01_E5_FIELDS} from '../src/es01ReviewPacket.js'
import {ES01_E7_MAX_BYTES,ES01_E7_STATES,compareES01ReviewerPackets,makeES01DifferenceReceipt} from '../src/es01ReviewerDifference.js'
const text=p=>readFileSync(p,'utf8')
const originals=JSON.parse(text('src/es01Evidence.json')).records
const clone=x=>JSON.parse(JSON.stringify(x))
assert.equal(ES01_E7_MAX_BYTES,262144)
assert.equal(ES01_E7_STATES.length,5)
assert.equal(ES01_E5_FIELDS.length,6)
for(const original of originals){
  const blank=makeES01ReviewPacket(original.id)
  const same=compareES01ReviewerPackets(blank,clone(blank))
  assert.equal(same.status,'STRUCTURAL_PAIR_ONLY')
  assert.equal(same.recordId,original.id)
  assert(same.allNotesIdentical)
  assert.equal(same.counts.BOTH_BLANK,6)
  assert.equal(same.evidenceAuthority,'NONE')
  assert.equal(same.reviewerIndependenceVerified,false)
  assert.equal(same.semanticAgreementEvaluated,false)
  assert.equal(same.gate,'HOLD_REVIEW_INCOMPLETE')
  const a=makeES01ReviewPacket(original.id,{fullMethods:'A method',benefitEndpoint:'Same words',harmEndpoint:'Only A',riskOfBias:'Possible confound'})
  const b=makeES01ReviewPacket(original.id,{fullMethods:'B method',benefitEndpoint:'Same words',comparability:'Only B',riskOfBias:'Possible confound'})
  const diff=compareES01ReviewerPackets(a,b)
  assert.equal(diff.status,'STRUCTURAL_PAIR_ONLY')
  assert.equal(diff.allNotesIdentical,false)
  assert.deepEqual(diff.fields.map(x=>x.status),['TEXT_DIFFERS','EXACT_TEXT_MATCH','ONLY_A_HAS_TEXT','ONLY_B_HAS_TEXT','EXACT_TEXT_MATCH','BOTH_BLANK'])
  assert.equal(diff.counts.TEXT_DIFFERS,1)
  assert.equal(diff.counts.EXACT_TEXT_MATCH,2)
  assert.equal(diff.counts.ONLY_A_HAS_TEXT,1)
  assert.equal(diff.counts.ONLY_B_HAS_TEXT,1)
  assert.equal(diff.counts.BOTH_BLANK,1)
  const receipt=makeES01DifferenceReceipt(diff)
  assert.equal(receipt.status,'STRUCTURAL_PAIR_ONLY')
  assert.equal(receipt.notesIncluded,false)
  assert.equal(receipt.independentReplicationVerified,false)
  assert.equal(receipt.gate,'HOLD_REVIEW_INCOMPLETE')
  assert(!JSON.stringify(receipt).includes('Possible confound'))
  assert(!JSON.stringify(receipt).includes('Same words'))
  assert(!('noteA' in receipt)&&!('noteB' in receipt))
  const altered=clone(a);altered.sourceCustody.sourceSupported='Guaranteed cure'
  assert.equal(compareES01ReviewerPackets(altered,b).status,'REJECTED')
  const claim=clone(b);claim.decisions.claimPromoted=true
  assert.equal(compareES01ReviewerPackets(a,claim).status,'REJECTED')
}
const a=makeES01ReviewPacket(originals[0].id)
