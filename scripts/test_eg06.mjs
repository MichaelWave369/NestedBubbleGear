import assert from 'node:assert/strict'
import { EG06, EG06_MODELS,fitEG06,predictEG06,runEG06 } from '../src/eg06Model.js'
let n=0;const check=(name,fn)=>{fn();n++;console.log('PASS EG06 '+name)}
const near=(a,b,eps=1e-10)=>assert(Math.abs(a-b)<eps,'expected '+a+' within '+eps+' of '+b)
check('registered comparison has two distinct source-labeled model families',()=>{
 assert.deepEqual(EG06_MODELS.map(x=>x.id),['C0','X1'])
 assert(EG06_MODELS.find(x=>x.id==='X1').origin.includes('NOT_LI_TORR'))
 assert(EG06_MODELS.find(x=>x.id==='C0').columns.length===5)
})
check('paired-mass reversed-gradient fixture has rank for both models',()=>{
 const r=runEG06({noiseN:0})
 assert.equal(r.rows.length,48)
 assert.equal(r.fixture.training,36)
 assert.equal(r.fixture.holdout,12)
 assert.equal(r.status,'MODEL_COMPARISON_ONLY')
 assert(r.conventional.identifiable&&r.extra.identifiable)
 assert(r.rows.every(x=>Number.isFinite(x.predictedC0N)&&Number.isFinite(x.predictedX1N)))
})
check('ground-truth null does not require a mass-like coefficient',()=>{
 const r=runEG06({noiseN:0})
 near(r.extra.coefficients.massDrive,0)
 near(r.extra.coefficients.gradientDrive,EG06.magneticMomentAm2)
 near(r.conventional.coefficients.thermal,EG06.thermalCoefficientN)
 near(r.conventional.coefficients.evenDrive,EG06.evenPickupN)
 assert(r.conventional.rmseN<1e-10)
 assert(r.extra.rmseN<1e-10)
 assert(r.evidence.deltaBIC<0,'baseline should have lower BIC on its exact clean null')
 assert.equal(r.evidence.favoredByBIC,'UNDECIDED','a single added parameter should not pass the preregistered strong threshold by itself')
})
check('software-injected term is recoverable in an otherwise clean fixture',()=>{
 const r=runEG06({massLikeFraction:.015,noiseN:0})
 near(r.extra.coefficients.massDrive,.015)
 assert(r.extra.rmseN<1e-10)
 assert(r.conventional.rmseN>0.001)
 assert(r.evidence.favoredByBIC==='X1')
 assert(r.conventional.holdoutRmseN>r.extra.holdoutRmseN)
})
check('mass-correlated ordinary artifact is observationally indistinguishable from injected mass term',()=>{
 const a=runEG06({massLikeFraction:.015,massCorrelatedArtifactFraction:0,noiseN:.0002})
 const b=runEG06({massLikeFraction:0,massCorrelatedArtifactFraction:.015,noiseN:.0002})
 assert.deepEqual(a.rows.map(x=>x.forceN),b.rows.map(x=>x.forceN))
 near(a.extra.coefficients.massDrive,b.extra.coefficients.massDrive)
 assert.equal(a.exactCausalCollision.status,'PHYSICAL_ORIGIN_NON_IDENTIFIABLE_EVEN_WHEN_X1_FIT_IS_FULL_RANK')
 assert.equal(b.evidence.favoredByBIC,'X1')
})
check('turning off mass contrast blocks the full extra-term model',()=>{
 const r=runEG06({massContrast:false})
 assert.equal(r.status,'REFUSED_NOT_IDENTIFIABLE')
 assert(r.conventional.identifiable)
 assert.equal(r.extra.identifiable,false)
 assert.equal(r.evidence,null)
})
check('turning off signed gradient reversal blocks baseline identification',()=>{
 const r=runEG06({gradientReversal:false})
 assert.equal(r.status,'REFUSED_NOT_IDENTIFIABLE')
 assert.equal(r.conventional.identifiable,false)
 assert.equal(r.extra.identifiable,false)
 assert.equal(r.evidence,null)
})
check('predictions and split remain deterministic, with a true future holdout',()=>{
 const a=runEG06({massKg:.12,gradientTPerM:1.2,noiseN:.0003}),b=runEG06({massKg:.12,gradientTPerM:1.2,noiseN:.0003})
 assert.deepEqual(a,b)
 assert(a.rows.filter(x=>x.phase==='HOLDOUT').every(x=>x.tick>=9))
 assert(a.rows.filter(x=>x.phase==='TRAIN').every(x=>x.tick<9))
 assert(Number.isFinite(a.conventional.holdoutRmseN))
 assert.equal(predictEG06(a.rows[0],a.extra),a.rows[0].predictedX1N)
})
check('no claim of reproduced historical gravitational force or physics discovery',()=>{
 const r=runEG06()
 assert.equal(r.provenance,'SIMULATED')
 assert.equal(r.authority,'NONE')
 assert(r.claim.includes('no measured gravity'))
 assert.equal(r.sourceBoundary.liTorr1991,'PUBLISHED_THEORY_NOT_RECONSTRUCTED')
 assert.equal(r.sourceBoundary.kowitt1994,'PUBLISHER_ABSTRACT_ONLY_FULL_CRITIQUE_PENDING')
})
check('rejects out-of-range and malformed test inputs',()=>{
 assert.throws(()=>runEG06({massKg:0}),RangeError)
 assert.throws(()=>runEG06({noiseN:-.01}),RangeError)
 assert.throws(()=>runEG06({massCorrelatedArtifactFraction:.5}),RangeError)
 assert.throws(()=>runEG06({gradientTPerM:0}),RangeError)
 assert.throws(()=>fitEG06([], 'missing'),RangeError)
})
console.log('EG06 '+n+'/'+n+' PASS · synthetic model comparison, holdout and causal-collision controls')
